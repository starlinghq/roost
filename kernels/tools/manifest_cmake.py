#!/usr/bin/env python3
"""Turn kernels/manifest.toml into CMake variables, so the manifest is the only place an SM list or a pin lives.

    python3 -I kernels/tools/manifest_cmake.py MANIFEST > roost_manifest.cmake
    python3 -I kernels/tools/manifest_cmake.py MANIFEST --sm-list      # 80;86;89;90;100;120

Emitted variables: ROOST_MANIFEST_SM_LIST, ROOST_UPSTREAMS (names), and for each upstream <i> in 0..n-1
ROOST_UPSTREAM_<i>_NAME, _REPO, _SHA, _PATCHES (list of "relative path|sha256").
"""

from __future__ import annotations

import sys
import tomllib
from pathlib import Path


def load(path: Path) -> dict:
    with path.open("rb") as handle:
        return tomllib.load(handle)


def sm_list(manifest: dict) -> list[int]:
    return [entry["arch"] for entry in manifest["sm"]]


def cmake_text(manifest: dict) -> str:
    lines = [
        "# Generated by kernels/tools/manifest_cmake.py from kernels/manifest.toml. Do not edit.",
        f'set(ROOST_MANIFEST_SM_LIST "{";".join(str(a) for a in sm_list(manifest))}")',
    ]
    upstreams = manifest.get("upstreams", [])
    lines.append(f'set(ROOST_UPSTREAMS "{";".join(u["name"] for u in upstreams)}")')
    for i, upstream in enumerate(upstreams):
        patches = ";".join(f"{p['path']}|{p['sha256']}" for p in upstream.get("patches", []))
        lines += [
            f'set(ROOST_UPSTREAM_{i}_NAME "{upstream["name"]}")',
            f'set(ROOST_UPSTREAM_{i}_REPO "{upstream["repo"]}")',
            f'set(ROOST_UPSTREAM_{i}_SHA "{upstream["sha"]}")',
            f'set(ROOST_UPSTREAM_{i}_PATCHES "{patches}")',
        ]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    if not argv:
        print(__doc__)
        return 2
    manifest = load(Path(argv[0]))
    if "--sm-list" in argv[1:]:
        print(";".join(str(a) for a in sm_list(manifest)))
    else:
        sys.stdout.write(cmake_text(manifest))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
