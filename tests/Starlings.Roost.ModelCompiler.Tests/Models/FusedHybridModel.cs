// A Qwen3.5-shaped hybrid at test size, in float32 so the graph evaluator can run it: three Gated DeltaNet layers (0, 1, 2) and
// one full-attention layer (3). Unlike HybridModel it follows the checkpoint's linear-attention block: ONE in_proj_qkv of
// [2*key_dim + value_dim, hidden], a causal convolution over all of those channels, then q, k and v as row-strided column views of
// the convolution output (GatedDeltaRuleArgs QStride, KStride, VStride, contract version 2), bound with value[start:end].
// There are more value heads than key heads (4 against 2) so the head grouping is exercised, and the rotary embedding covers
// half of the head. Two outputs: the first layer's mixer output (for an independent transcription) and the logits.
