using Starlings.Roost.Worker.Tests.Support;

/// <summary>The GPU phase's output, read by the CPU phase: tokens, logits per step and the traced op outputs of chosen steps.</summary>
internal sealed class Dump
{
    private const string Magic = "R025-GPU-DUMP-1";

    public required string Device { get; init; }

    public required int Sm { get; init; }

    public required string LibrarySha256 { get; init; }

    public List<PromptDump> Prompts { get; } = [];

    public void Save(string path)
    {
        using var w = new BinaryWriter(File.Create(path));
        w.Write(Magic);
        w.Write(Device);
        w.Write(Sm);
        w.Write(LibrarySha256);
        w.Write(Prompts.Count);
        foreach (var p in Prompts)
        {
            w.Write(p.Name);
            WriteInts(w, p.Ids);
            WriteInts(w, p.Tokens);
            w.Write(p.Logits.Count);
            foreach (var l in p.Logits)
            {
                WriteFloats(w, l);
            }

            w.Write(p.Traced.Count);
            foreach (var (step, snaps) in p.Traced)
            {
                w.Write(step);
                w.Write(snaps.Count);
                foreach (var s in snaps)
                {
                    w.Write(s.Ordinal);
                    w.Write(s.Layer);
                    w.Write(s.Op);
                    w.Write(s.What);
                    WriteFloats(w, s.Values);
                }
            }
        }
    }

    public static Dump Load(string path)
    {
        using var r = new BinaryReader(File.OpenRead(path));
        if (r.ReadString() != Magic)
        {
            throw new InvalidDataException("not a GPU dump");
        }

        var d = new Dump { Device = r.ReadString(), Sm = r.ReadInt32(), LibrarySha256 = r.ReadString() };
        int prompts = r.ReadInt32();
        for (int i = 0; i < prompts; i++)
        {
            var p = new PromptDump { Name = r.ReadString(), Ids = ReadInts(r), Tokens = ReadInts(r) };
            int steps = r.ReadInt32();
            for (int s = 0; s < steps; s++)
            {
                p.Logits.Add(ReadFloats(r));
            }

            int traced = r.ReadInt32();
            for (int t = 0; t < traced; t++)
            {
                int step = r.ReadInt32();
                int count = r.ReadInt32();
                var list = new List<Snapshot>(count);
                for (int c = 0; c < count; c++)
                {
                    list.Add(new Snapshot(r.ReadInt32(), r.ReadInt32(), r.ReadString(), r.ReadString(), ReadFloats(r)));
                }

                p.Traced[step] = list;
            }

            d.Prompts.Add(p);
        }

        return d;
    }

    private static void WriteInts(BinaryWriter w, int[] v)
    {
        w.Write(v.Length);
        foreach (int x in v)
        {
            w.Write(x);
        }
    }

    private static int[] ReadInts(BinaryReader r)
    {
        var v = new int[r.ReadInt32()];
        for (int i = 0; i < v.Length; i++)
        {
            v[i] = r.ReadInt32();
        }

        return v;
    }

    private static void WriteFloats(BinaryWriter w, float[] v)
    {
        w.Write(v.Length);
        var bytes = new byte[v.Length * 4];
        Buffer.BlockCopy(v, 0, bytes, 0, bytes.Length);
        w.Write(bytes);
    }

    private static float[] ReadFloats(BinaryReader r)
    {
        var v = new float[r.ReadInt32()];
        var bytes = r.ReadBytes(v.Length * 4);
        Buffer.BlockCopy(bytes, 0, v, 0, bytes.Length);
        return v;
    }
}

internal sealed class PromptDump
{
    public required string Name { get; init; }

    /// <summary>Prompt token ids.</summary>
    public required int[] Ids { get; init; }

    /// <summary>Greedy tokens generated by the GPU: Tokens[0] follows the prompt.</summary>
    public required int[] Tokens { get; init; }

    /// <summary>Logits of the step that produced Tokens[i], one vocabulary row per step.</summary>
    public List<float[]> Logits { get; } = [];

    /// <summary>Op outputs of the traced steps, keyed by step index (0 is the prefill).</summary>
    public Dictionary<int, List<Snapshot>> Traced { get; } = [];
}

