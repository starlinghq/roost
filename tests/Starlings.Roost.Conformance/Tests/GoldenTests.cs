using System.Text;
using System.Text.Json;
using Starlings.Roost.Abi;

namespace Starlings.Roost.Conformance.Tests;

public sealed class GoldenTests
{
    /// <summary>The goldens asset, a release file that is never committed: set ROOST_CONFORMANCE_GOLDENS to its path.</summary>
    private static string? AssetPath => Environment.GetEnvironmentVariable("ROOST_CONFORMANCE_GOLDENS") is { Length: > 0 } p && File.Exists(p) ? p : null;

    private static string LockPath => Path.Combine(AppContext.BaseDirectory, GoldenLock.FileName);

    [Fact]
    public void TheCommittedLockPinsAnAssetByDigest()
    {
        GoldenLock l = GoldenLock.Load(LockPath);
        Assert.Equal("roost-conformance-goldens.safetensors", l.Asset);
        Assert.Matches("^[0-9a-f]{64}$", l.Sha256);
        Assert.Matches("^[0-9a-f]{64}$", l.GeneratorSha256);
        Assert.True(l.CaseCount > 0);
        Assert.True(l.SizeBytes > 0);
    }

    [Fact]
    public void TheAssetIsNotInTheRepository()
    {
        // Goldens are release assets: neither the file nor any safetensors file sits next to the suite.
        string dir = Path.GetFullPath(Path.Combine(AppContext.BaseDirectory, "..", "..", "..", "goldens"));
        if (Directory.Exists(dir))
        {
            Assert.Empty(Directory.EnumerateFiles(dir, "*.safetensors", SearchOption.AllDirectories));
        }
    }

    [Fact]
    public void RealGoldensMatchTheLockAndCpuOpsAgreesWithEveryUpstreamCase()
    {
        Assert.SkipUnless(AssetPath is not null, "ROOST_CONFORMANCE_GOLDENS does not point to the goldens asset (a release file, generated by goldens/generate_goldens.py)");
        using GoldenSet g = GoldenSet.Open(AssetPath!, LockPath);
        using var cpu = new CpuBackend();
        ConformanceReport r = Fixtures.RunOn(cpu, Fixtures.Options(goldens: g, determinism: false, invariance: false));
        var golden = r.Results.Where(x => x.Source == "golden").ToList();
        Assert.Equal(GoldenLock.Load(LockPath).CaseCount, golden.Count);
        var bad = golden.Where(x => x.Outcome != "pass").Select(x => $"{x.Case}: {x.Outcome} {x.Detail} {string.Join(',', x.Outputs.Select(o => $"{o.Name}:{o.Stat.MaxUtilisation:F3}/{o.Stat.Violations}"))}").ToList();
        Assert.Empty(bad);
    }

    [Fact]
    public void WithoutGoldensTheGoldenCasesAreNotRunAndNeverPass()
    {
        using var cpu = new CpuBackend();
        ConformanceReport r = Fixtures.RunOn(cpu, Fixtures.Options(variants: new HashSet<string> { CpuBackend.VariantId }, ops: new HashSet<OpId> { OpId.Embedding }));
        Assert.Contains(r.Results, x => x.Case == "(goldens)" && x.Outcome == "not_run");
        Assert.DoesNotContain(r.Results, x => x.Source == "golden" && x.Outcome == "pass");
    }

    [Fact]
    public void ASyntheticGoldensFileIsReadRunAndCheckedAgainstItsLock()
    {
        string dir = Path.Combine(Path.GetTempPath(), "roost-golden-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(dir);
        try
        {
            string asset = Path.Combine(dir, "g.safetensors");
            WriteSynthetic(asset, tamper: false);
            string lockFile = Path.Combine(dir, "g.lock.json");
            File.WriteAllText(lockFile, JsonSerializer.Serialize(new
            {
                asset = new { name = "g.safetensors", sha256 = RunEnvironment.Digest(asset), size_bytes = new FileInfo(asset).Length },
                generator = new { sha256 = new string('0', 64) },
                case_count = 2,
            }));
            using (GoldenSet g = GoldenSet.Open(asset, lockFile))
            using (var cpu = new CpuBackend())
            {
                ConformanceReport r = Fixtures.RunOn(cpu, Fixtures.Options(goldens: g, variants: new HashSet<string> { CpuBackend.VariantId }, ops: new HashSet<OpId> { OpId.Residual, OpId.Embedding }, determinism: false, invariance: false));
                var golden = r.Results.Where(x => x.Source == "golden").ToList();
                Assert.Equal(2, golden.Count);
                Assert.All(golden, x => Assert.Equal("pass", x.Outcome));
                Assert.All(golden, x => Assert.Equal("golden", x.Reference));
            }

            // Another byte in the asset: the lock refuses it.
            string other = Path.Combine(dir, "other.safetensors");
            WriteSynthetic(other, tamper: true);
            Assert.Throws<InvalidDataException>(() => GoldenSet.Open(other, lockFile));
            // The same bytes but a wrong expected value: no lock, so it opens, and the case fails.
            using (GoldenSet g = GoldenSet.Open(other, null))
            using (var cpu = new CpuBackend())
            {
                ConformanceReport r = Fixtures.RunOn(cpu, Fixtures.Options(goldens: g, variants: new HashSet<string> { CpuBackend.VariantId }, ops: new HashSet<OpId> { OpId.Embedding }, determinism: false, invariance: false));
                Assert.Contains(r.Results, x => x.Source == "golden" && x.Outcome == "fail");
            }
        }
        finally
        {
            Directory.Delete(dir, true);
        }
    }

    [Fact]
    public void AFileThatIsNotAGoldensFileIsRefused()
    {
        string path = Path.Combine(Path.GetTempPath(), "roost-notgolden-" + Guid.NewGuid().ToString("N") + ".safetensors");
        try
        {
            WriteSafeTensors(path, [], new Dictionary<string, string> { ["format"] = "something-else" });
            Assert.Throws<InvalidDataException>(() => GoldenSet.Open(path, null));
        }
        finally
        {
            File.Delete(path);
        }
    }

    private static void WriteSynthetic(string path, bool tamper)
    {
        // Embedding: a 4 x 3 bf16 table, ids [2, 0, 3]; expected rows copied. Residual: f32 a + b, expected in float64.
        ushort[] table = new ushort[12];
        for (int i = 0; i < table.Length; i++)
        {
            table[i] = Elem.ToBf16((i * 0.37f) - 2f);
        }

        var ids = new[] { 2, 0, 3 };
        ushort[] expected = new ushort[9];
        for (int t = 0; t < 3; t++)
        {
            Array.Copy(table, ids[t] * 3, expected, t * 3, 3);
        }

        if (tamper)
        {
            expected[4] ^= 1;
        }

        float[] a = [1f, 2f, 3f, 4f], bb = [0.5f, 0.25f, -1f, 1e-3f];
        double[] sum = [.. a.Zip(bb, (x, y) => (double)x + y)];
        var tensors = new Dictionary<string, (string Dtype, long[] Shape, byte[] Data)>
        {
            ["emb/table"] = ("BF16", [4, 3], Bytes(table)),
            ["emb/ids"] = ("I32", [3], Bytes(ids)),
            ["emb/expected/out"] = ("BF16", [3, 3], Bytes(expected)),
            ["res/a"] = ("F32", [4], Bytes(a)),
            ["res/b"] = ("F32", [4], Bytes(bb)),
            ["res/expected/out"] = ("F64", [4], Bytes(sum)),
        };
        string cases = JsonSerializer.Serialize(new[]
        {
            new Dictionary<string, object?>
            {
                ["id"] = "emb", ["op"] = "Embedding", ["dtype"] = "BF16", ["class"] = "exact", ["seed"] = 1,
                ["params"] = new Dictionary<string, double> { ["tokens"] = 3, ["dim"] = 3, ["vocab"] = 4 },
                ["inputs"] = new[] { "table", "ids" },
                ["outputs"] = new[] { new Dictionary<string, string> { ["name"] = "out", ["dtype"] = "BF16" } },
                ["scale_buffer"] = null,
            },
            new Dictionary<string, object?>
            {
                ["id"] = "res", ["op"] = "Residual", ["dtype"] = "F32", ["class"] = "elementwise-f32", ["seed"] = 2,
                ["params"] = new Dictionary<string, double> { ["elements"] = 4 },
                ["inputs"] = new[] { "a", "b" },
                ["outputs"] = new[] { new Dictionary<string, string> { ["name"] = "out", ["dtype"] = "F32" } },
                ["scale_buffer"] = null,
            },
        });
        WriteSafeTensors(path, tensors, new Dictionary<string, string> { ["format"] = "roost.conformance-goldens", ["format_version"] = "1", ["cases"] = cases });
    }

    private static byte[] Bytes<T>(T[] v) where T : unmanaged => System.Runtime.InteropServices.MemoryMarshal.AsBytes<T>(v).ToArray();

    private static void WriteSafeTensors(string path, Dictionary<string, (string Dtype, long[] Shape, byte[] Data)> tensors, Dictionary<string, string> metadata)
    {
        var header = new Dictionary<string, object> { ["__metadata__"] = metadata };
        long offset = 0;
        foreach ((string name, var t) in tensors.OrderBy(k => k.Key, StringComparer.Ordinal))
        {
            header[name] = new { dtype = t.Dtype, shape = t.Shape, data_offsets = new[] { offset, offset + t.Data.Length } };
            offset += t.Data.Length;
        }

        byte[] json = Encoding.UTF8.GetBytes(JsonSerializer.Serialize(header));
        int pad = (8 - (json.Length % 8)) % 8;
        using FileStream f = File.Create(path);
        f.Write(BitConverter.GetBytes((ulong)(json.Length + pad)));
        f.Write(json);
        f.Write(Enumerable.Repeat((byte)' ', pad).ToArray());
        foreach ((_, var t) in tensors.OrderBy(k => k.Key, StringComparer.Ordinal))
        {
            f.Write(t.Data);
        }
    }
}
