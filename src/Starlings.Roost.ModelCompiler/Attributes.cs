namespace Starlings.Roost.ModelCompiler;

/// <summary>The definition attributes, emitted into every compilation that references the generator (post-initialisation output).</summary>
internal static class Attributes
{
    internal const string Namespace = "Starlings.Roost.ModelCompiler";
    internal const string Model = Namespace + ".RoostModelAttribute";
    internal const string Dim = Namespace + ".DimAttribute";
    internal const string Weight = Namespace + ".WeightAttribute";
    internal const string StateGroup = Namespace + ".StateGroupAttribute";
    internal const string Node = Namespace + ".NodeAttribute";
    internal const string Output = Namespace + ".OutputAttribute";

    internal const string Source = @"// <auto-generated/>
#nullable enable
using System;

namespace Starlings.Roost.ModelCompiler
{
/// <summary>Marks a static partial class as a Roost model definition; the generator emits its graph, slots, state groups and Forward&lt;TOps&gt;.</summary>
[AttributeUsage(AttributeTargets.Class, Inherited = false)]
internal sealed class RoostModelAttribute : Attribute
{
    public RoostModelAttribute(string name) => Name = name;

    public string Name { get; }

    /// <summary>Activation element type (a Starlings.Roost.Abi.DType name); BF16 when omitted.</summary>
    public string Dtype { get; set; } = ""BF16"";
}

/// <summary>A named integer constant (an integer expression over earlier dims) usable in shapes and integer arguments.</summary>
[AttributeUsage(AttributeTargets.Class, AllowMultiple = true, Inherited = false)]
internal sealed class DimAttribute : Attribute
{
    public DimAttribute(string name, int value) { Name = name; Value = value.ToString(System.Globalization.CultureInfo.InvariantCulture); }

    public DimAttribute(string name, string expression) { Name = name; Value = expression; }

    public string Name { get; }

    public string Value { get; }
}

/// <summary>One weight slot of the loader, in declaration order. Layers repeats it per layer ({i} in the strings).</summary>
[AttributeUsage(AttributeTargets.Class, AllowMultiple = true, Inherited = false)]
internal sealed class WeightAttribute : Attribute
{
    public WeightAttribute(string name, string shape) { Name = name; Shape = shape; }

    public string Name { get; }

    /// <summary>Comma-separated dim expressions, for example ""vocab,hidden"".</summary>
    public string Shape { get; }

    public string? Dtype { get; set; }

    /// <summary>The checkpoint tensor name the loader reads this slot from.</summary>
    public string? Source { get; set; }

    public string? Layers { get; set; }

    /// <summary>The slot is loaded but no node of this definition reads it yet (an op the vocabulary lacks would); no ROOST014 for it.</summary>
    public bool Reserved { get; set; }
}

/// <summary>One state group (contract C4). Kind is Full, Sliding or Recurrent. Layers selects the layers that hold state in it.</summary>
[AttributeUsage(AttributeTargets.Class, AllowMultiple = true, Inherited = false)]
internal sealed class StateGroupAttribute : Attribute
{
    public StateGroupAttribute(string name, string kind) { Name = name; Kind = kind; }

    public string Name { get; }

    public string Kind { get; }

    public string? Layers { get; set; }

    public string KvHeads { get; set; } = """";

    public string HeadSize { get; set; } = """";

    public string BlockSize { get; set; } = """";

    public string? Dtype { get; set; }

    /// <summary>Recurrent: the per-layer state shape (comma-separated dim expressions).</summary>
    public string StateShape { get; set; } = """";

    /// <summary>Recurrent: the per-layer convolution state shape, when the layer has one.</summary>
    public string ConvShape { get; set; } = """";

    public string? ConvDtype { get; set; }

    public string Window { get; set; } = """";

    public string SnapshotSlots { get; set; } = """";
}

/// <summary>One node of the op graph, in topological order. Args is a ';'-separated list of FIELD=binding pairs.</summary>
[AttributeUsage(AttributeTargets.Class, AllowMultiple = true, Inherited = false)]
internal sealed class NodeAttribute : Attribute
{
    public NodeAttribute(string name, string op, string args) { Name = name; Op = op; Args = args; }

    public string Name { get; }

    public string Op { get; }

    public string Args { get; }

    /// <summary>Repeat for these layers: ranges 'a:b' (b excluded) with an optional '%m=r' or '%m!=r' filter, comma-separated.</summary>
    public string? Layers { get; set; }
}

/// <summary>Names a value as a model output.</summary>
[AttributeUsage(AttributeTargets.Class, AllowMultiple = true, Inherited = false)]
internal sealed class OutputAttribute : Attribute
{
    public OutputAttribute(string name) => Name = name;

    public string Name { get; }
}
}
";
}
