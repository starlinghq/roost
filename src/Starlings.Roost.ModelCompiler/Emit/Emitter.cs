using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using Starlings.Roost.Graph;

namespace Starlings.Roost.ModelCompiler;

/// <summary>
/// Lowers the graph to C#: the loader slot order, the state-group descriptors, the plan input layout, the graph
/// itself and <c>Forward&lt;TOps&gt;</c>. The output is plain struct code over static abstract calls, so it
/// allocates nothing and needs no reflection under JIT or Native AOT. Line endings are always \n.
/// </summary>
internal static class Emitter
{
    private const string Ops = "global::Starlings.Roost.Ops.IRoostOps";
    private const string DType = "global::Starlings.Roost.Abi.DType";
    private const string Span = "global::Starlings.Roost.DeviceSpan";
    private const string G = "global::Starlings.Roost.Graph.";

    public static string Emit(ModelSpec spec, Vocabulary vocab, BuiltModel m, BufferPlan plan)
    {
        var w = new Writer();
        var graph = m.Graph;
        var opsByName = vocab.Ops.ToDictionary(o => o.Name, StringComparer.Ordinal);
        int weightCount = m.Weights.Count;

        w.Line("// <auto-generated/>");
        w.Line("// Roost model compiler: " + Writer.Comment(spec.ModelName));
        w.Line("#nullable enable");
        w.Line("#pragma warning disable");
        if (spec.Namespace.Length > 0)
        {
            w.Line("namespace " + spec.Namespace);
            w.Open();
        }

        w.Line("public static unsafe partial class " + spec.ClassName);
        w.Open();

        w.Line("/// <summary>The model name.</summary>");
        w.Line("public const string ModelName = " + Writer.Lit(spec.ModelName) + ";");
        w.Line("/// <summary>Every op the graph uses.</summary>");
        w.Line("public static readonly string[] UsedOps = { " + string.Join(", ", m.UsedOps.Select(Writer.Lit)) + " };");
        w.Line();

        EmitWeights(w, m);
        EmitState(w, m, vocab);
        EmitPlanAndLayout(w, m, plan);
        EmitContext(w);
        EmitGraph(w, m, vocab);
        EmitCheck(w, m, vocab, opsByName);
        EmitHelpers(w);
        EmitForward(w, m, plan, opsByName, weightCount);
        EmitOutputs(w, m, plan, weightCount);

        w.Close();
        if (spec.Namespace.Length > 0)
        {
            w.Close();
        }

        return w.ToString();
    }

    // ---- weights, state, plan ----------------------------------------------------------------------------

    private static void EmitWeights(Writer w, BuiltModel m)
    {
        w.Line("/// <summary>One weight slot of the loader: its order in <see cref=\"WeightSlots\"/> is its index in <c>StepContext.Weights</c>.</summary>");
        w.Line("public readonly struct WeightSlot");
        w.Open();
        w.Line("public WeightSlot(string name, string? source, " + DType + " dtype, long elements, string shape, int layer) { Name = name; Source = source; Dtype = dtype; Elements = elements; Shape = shape; Layer = layer; }");
        w.Line("public string Name { get; }");
        w.Line("public string? Source { get; }");
        w.Line("public " + DType + " Dtype { get; }");
        w.Line("public long Elements { get; }");
        w.Line("public string Shape { get; }");
        w.Line("/// <summary>The layer a repeated slot belongs to; -1 for a slot outside the layers.</summary>");
        w.Line("public int Layer { get; }");
        w.Close();
        w.Line("/// <summary>The weight loader slot order, from the order of the [Weight] attributes (layer by layer for repeated blocks).</summary>");
        w.Line("public static readonly WeightSlot[] WeightSlots =");
        w.Line("{");
        foreach (var s in m.Weights)
        {
            w.Line("    new WeightSlot(" + Writer.Lit(s.Name) + ", " + (s.Source is null ? "null" : Writer.Lit(s.Source)) + ", " + DType + "." + s.Dtype + ", " + s.Elements.ToString(CultureInfo.InvariantCulture) + "L, " + Writer.Lit(string.Join(",", s.Shape)) + ", " + (s.Layer ?? -1).ToString(CultureInfo.InvariantCulture) + "),");
        }

        w.Line("};");
        w.Line();
    }

    private static void EmitState(Writer w, BuiltModel m, Vocabulary vocab)
    {
        w.Line("/// <summary>One per-layer state tensor (a K or V cache, a recurrent state or a convolution state) in <c>StepContext.State</c>.</summary>");
        w.Line("public readonly struct StateSlot");
        w.Open();
        w.Line("public StateSlot(string name, int group, int layer, string role, " + DType + " dtype, long elementsPerBlock) { Name = name; Group = group; Layer = layer; Role = role; Dtype = dtype; ElementsPerBlock = elementsPerBlock; }");
        w.Line("public string Name { get; }");
        w.Line("public int Group { get; }");
        w.Line("public int Layer { get; }");
        w.Line("public string Role { get; }");
        w.Line("public " + DType + " Dtype { get; }");
        w.Line("/// <summary>Elements of one block (paged groups) or one slot (recurrent groups).</summary>");
        w.Line("public long ElementsPerBlock { get; }");
        w.Close();
        w.Line("/// <summary>The state tensors in the order of <c>StepContext.State</c>: by group, then layer, then role.</summary>");
        w.Line("public static readonly StateSlot[] StateSlots =");
        w.Line("{");
        foreach (var s in m.StateSlots)
        {
            w.Line("    new StateSlot(" + Writer.Lit(s.Name) + ", " + s.Group.ToString(CultureInfo.InvariantCulture) + ", " + s.Layer.ToString(CultureInfo.InvariantCulture) + ", " + Writer.Lit(s.Role) + ", " + DType + "." + s.Dtype + ", " + s.ElementsPerBlock.ToString(CultureInfo.InvariantCulture) + "L),");
        }

        w.Line("};");
        w.Line();
        if (!vocab.HasStateTypes)
        {
            return;
        }

        const string S = "global::Starlings.Roost.State.";
        w.Line("/// <summary>The state-group descriptors (contract C4) of this model, indexed as the step plan indexes groups.</summary>");
        w.Line("public static global::System.Collections.Immutable.ImmutableArray<" + S + "StateGroupDescriptor> CreateStateGroups()");
        w.Open();
        w.Line("var b = global::System.Collections.Immutable.ImmutableArray.CreateBuilder<" + S + "StateGroupDescriptor>(" + m.Groups.Count.ToString(CultureInfo.InvariantCulture) + ");");
        foreach (var g in m.Groups)
        {
            bool recurrent = g.Kind == "Recurrent";
            string layers = recurrent
                ? "global::System.Collections.Immutable.ImmutableArray<" + S + "LayerKvShape>.Empty"
                : "global::System.Collections.Immutable.ImmutableArray.Create(" + string.Join(", ", g.Layers.Select(l => "new " + S + "LayerKvShape(" + l.ToString(CultureInfo.InvariantCulture) + ", " + g.KvHeads.ToString(CultureInfo.InvariantCulture) + ", " + g.HeadSize.ToString(CultureInfo.InvariantCulture) + ")")) + ")";
            var sb = new StringBuilder();
            sb.Append("b.Add(new " + S + "StateGroupDescriptor { Index = " + g.Index.ToString(CultureInfo.InvariantCulture));
            sb.Append(", Name = " + Writer.Lit(g.Name));
            sb.Append(", Kind = " + S + "StateGroupKind." + g.Kind);
            sb.Append(", Layers = " + layers);
            sb.Append(", BlockSize = " + g.BlockSize.ToString(CultureInfo.InvariantCulture));
            sb.Append(", DType = " + DType + "." + g.Dtype);
            sb.Append(", BytesPerBlock = " + g.BytesPerBlock.ToString(CultureInfo.InvariantCulture) + "L");
            if (g.Window > 0)
            {
                sb.Append(", Window = " + g.Window.ToString(CultureInfo.InvariantCulture));
            }

            if (recurrent)
            {
                sb.Append(", RecurrentStateShape = global::System.Collections.Immutable.ImmutableArray.Create<long>(" + string.Join(", ", g.StateShape.Select(d => d.ToString(CultureInfo.InvariantCulture) + "L")) + ")");
                if (g.SnapshotSlots > 0)
                {
                    sb.Append(", SnapshotSlots = " + g.SnapshotSlots.ToString(CultureInfo.InvariantCulture));
                }
            }

            sb.Append(" });");
            w.Line(sb.ToString());
        }

        w.Line("return b.ToImmutable();");
        w.Close();
        w.Line();
    }

    private static string CountExpr(string count, string tokens, string selected, string seqs, string blocks)
    {
        switch (count)
        {
            case "tokens":
                return tokens;
            case "selected":
                return selected;
            case "seqs":
                return seqs;
            case "seqs+1":
                return "(" + seqs + " + 1)";
            default:
                return blocks;
        }
    }

    private static void EmitPlanAndLayout(Writer w, BuiltModel m, BufferPlan plan)
    {
        w.Line("/// <summary>Sizes of one worker's allocations for the largest step it will run: the activation arena and the plan input region.</summary>");
        w.Line("public readonly struct ForwardLayout");
        w.Open();
        w.Line("/// <summary>Token region bytes per token of capacity, after buffer reuse (build-time constant).</summary>");
        w.Line("public const long PerTokenBytes = " + plan.PerTokenBytes.ToString(CultureInfo.InvariantCulture) + "L;");
        w.Line("/// <summary>Bytes of the fixed (not token-major) region (build-time constant).</summary>");
        w.Line("public const long FixedBytes = " + plan.FixedBytes.ToString(CultureInfo.InvariantCulture) + "L;");
        w.Line("/// <summary>Token capacities are rounded up to this, so every arena buffer starts on a 16-byte boundary or better.</summary>");
        w.Line("public const int TokenAlignment = 64;");
        w.Line("public ForwardLayout(int maxTokens, int maxSequences, int maxKvBlocks)");
        w.Open();
        w.Line("MaxTokens = maxTokens; MaxSequences = maxSequences; MaxKvBlocks = maxKvBlocks;");
        w.Line("CapacityTokens = (maxTokens + TokenAlignment - 1) / TokenAlignment * TokenAlignment;");
        w.Line("long off = 0;");
        foreach (var pi in m.PlanInputs)
        {
            string cnt = CountExpr(pi.Count, "CapacityTokens", "CapacityTokens", "maxSequences", "maxKvBlocks");
            w.Line(pi.Field + "Offset = off; off += ((long)" + cnt + " * " + ModelBuilder.ByteSize(pi.Dtype).ToString(CultureInfo.InvariantCulture) + " + 63) / 64 * 64;");
        }

        w.Line("PlanBytes = off;");
        w.Close();
        w.Line("public int MaxTokens { get; }");
        w.Line("public int MaxSequences { get; }");
        w.Line("public int MaxKvBlocks { get; }");
        w.Line("/// <summary>MaxTokens rounded up to <see cref=\"TokenAlignment\"/>; the stride unit of the token region.</summary>");
        w.Line("public int CapacityTokens { get; }");
        w.Line("public long PlanBytes { get; }");
        w.Line("public long FixedRegionOffset => (PerTokenBytes * CapacityTokens + 255) / 256 * 256;");
        w.Line("/// <summary>Bytes of activation arena the worker allocates once.</summary>");
        w.Line("public long ArenaBytes => FixedRegionOffset + FixedBytes;");
        foreach (var pi in m.PlanInputs)
        {
            w.Line("public long " + pi.Field + "Offset { get; }");
        }

        w.Close();
        w.Line();

        w.Line("/// <summary>The step inputs this model's ops read, from the C3 argument structs they use. Fill the region at the offsets of <see cref=\"ForwardLayout\"/> (or let Bind slice it).</summary>");
        w.Line("public struct PlanInputs");
        w.Open();
        w.Line("/// <summary>The inputs, in region order: name, element type, count (tokens, selected, seqs, seqs+1, kv_blocks).</summary>");
        w.Line("public static readonly (string Name, " + DType + " Dtype, string Count)[] Layout =");
        w.Line("{");
        foreach (var pi in m.PlanInputs)
        {
            w.Line("    (" + Writer.Lit(pi.Field) + ", " + DType + "." + pi.Dtype + ", " + Writer.Lit(pi.Count) + "),");
        }

        w.Line("};");
        foreach (var pi in m.PlanInputs)
        {
            w.Line("public " + Span + " " + pi.Field + ";");
        }

        w.Line("/// <summary>Slices <paramref name=\"region\"/> (<see cref=\"ForwardLayout.PlanBytes\"/> bytes) into the inputs of a step with the given counts.</summary>");
        w.Line("public static PlanInputs Bind(" + Span + " region, in ForwardLayout layout, int tokens, int selected, int sequences, int kvBlocks)");
        w.Open();
        w.Line("PlanInputs p = default;");
        foreach (var pi in m.PlanInputs)
        {
            string cnt = CountExpr(pi.Count, "tokens", "selected", "sequences", "kvBlocks");
            w.Line("p." + pi.Field + " = new " + Span + " { Address = region.Address + (nint)layout." + pi.Field + "Offset, Length = (ulong)" + cnt + ", Dtype = " + DType + "." + pi.Dtype + " };");
        }

        w.Line("return p;");
        w.Close();
        w.Close();
        w.Line();
    }

    private static void EmitContext(Writer w)
    {
        w.Line("/// <summary>Everything one forward call reads. A ref struct over caller-owned memory, so building it allocates nothing.</summary>");
        w.Line("public readonly ref struct StepContext");
        w.Open();
        w.Line("public StepContext(in ForwardLayout layout, " + Span + " arena, global::System.ReadOnlySpan<" + Span + "> weights, global::System.ReadOnlySpan<" + Span + "> state, in PlanInputs plan, int tokens, int selected, int sequences, int kvBlocks)");
        w.Open();
        w.Line("Layout = layout; Arena = arena; Weights = weights; State = state; Plan = plan; Tokens = tokens; Selected = selected; Sequences = sequences; KvBlocks = kvBlocks;");
        w.Close();
        w.Line("public ForwardLayout Layout { get; }");
        w.Line("/// <summary>The activation arena (ArenaBytes bytes).</summary>");
        w.Line("public " + Span + " Arena { get; }");
        w.Line("/// <summary>One span per entry of <see cref=\"WeightSlots\"/>, in that order.</summary>");
        w.Line("public global::System.ReadOnlySpan<" + Span + "> Weights { get; }");
        w.Line("/// <summary>One span per entry of <see cref=\"StateSlots\"/>, in that order.</summary>");
        w.Line("public global::System.ReadOnlySpan<" + Span + "> State { get; }");
        w.Line("public PlanInputs Plan { get; }");
        w.Line("public int Tokens { get; }");
        w.Line("/// <summary>Rows the head selects (logits rows).</summary>");
        w.Line("public int Selected { get; }");
        w.Line("public int Sequences { get; }");
        w.Line("/// <summary>Entries of the block-index plan input.</summary>");
        w.Line("public int KvBlocks { get; }");
        w.Close();
        w.Line();
    }

    // ---- graph -------------------------------------------------------------------------------------------

    private static void EmitGraph(Writer w, BuiltModel m, Vocabulary vocab)
    {
        if (!vocab.HasGraphTypes)
        {
            return;
        }

        w.Line("/// <summary>The unfused C7 graph of this model (every node's Origin is itself), for passes and the graph checker.</summary>");
        w.Line("public static " + G + "OpGraph BuildGraph()");
        w.Open();
        w.Line("var values = new global::System.Collections.Generic.List<" + G + "GraphValue>(" + m.Graph.Values.Count.ToString(CultureInfo.InvariantCulture) + ");");
        foreach (var v in m.Graph.Values)
        {
            string shape = "new " + G + "ShapeDim[] { " + string.Join(", ", v.Shape.Select(d => d.IsSymbolic ? G + "ShapeDim.Named(" + Writer.Lit(d.Symbol!) + ")" : G + "ShapeDim.Of(" + d.Size.ToString(CultureInfo.InvariantCulture) + "L)")) + " }";
            w.Line("values.Add(new " + G + "GraphValue(" + v.Id.ToString(CultureInfo.InvariantCulture) + ", " + Writer.Lit(v.Name) + ", " + G + "ValueKind." + v.Kind + ", " + shape + ", " + G + "GraphDType." + v.DType + ", " + G + "GraphLayout." + v.Layout + ", " + G + "Sharding.Replicated));");
        }

        w.Line("var nodes = new global::System.Collections.Generic.List<" + G + "OpNode>(" + m.Graph.Nodes.Count.ToString(CultureInfo.InvariantCulture) + ");");
        foreach (var n in m.Graph.Nodes)
        {
            string attrs = string.Join(", ", n.Attributes.OrderBy(a => a.Key, StringComparer.Ordinal).Select(a => "{ " + Writer.Lit(a.Key) + ", " + Writer.Lit(a.Value) + " }"));
            w.Line("nodes.Add(new " + G + "OpNode(" + n.Id.ToString(CultureInfo.InvariantCulture) + ", " + Writer.Lit(n.Op) + ", new int[] { " + string.Join(", ", n.Inputs) + " }, new int[] { " + string.Join(", ", n.Outputs) + " }, new global::System.Collections.Generic.Dictionary<string, string> { " + attrs + " }, new int[] { " + string.Join(", ", n.Origin) + " }, null));");
        }

        w.Line("return new " + G + "OpGraph(ModelName, values, nodes, true);");
        w.Close();
        w.Line();
    }

    private static void EmitCheck(Writer w, BuiltModel m, Vocabulary vocab, Dictionary<string, OpInfo> ops)
    {
        var reserved = m.UsedOps.Where(o => !ops[o].IsAbstract && !ops[o].HasSupportsFlag).ToList();
        w.Line("/// <summary>Throws when <typeparamref name=\"TOps\"/> lacks an op this model uses that IRoostOps only reserves (the abstract ops are checked by the compiler). Call once at load; it allocates only when it throws.</summary>");
        w.Line("public static void CheckBackend<TOps>() where TOps : struct, " + Ops);
        w.Open();
        if (reserved.Count > 0 && vocab.HasOpId)
        {
            w.Line("string? missing = null;");
            foreach (string op in reserved)
            {
                w.Line("if (!TOps.Supports(global::Starlings.Roost.Abi.OpId." + op + ")) { missing = missing is null ? " + Writer.Lit(op) + " : missing + \", \" + " + Writer.Lit(op) + "; }");
            }

            w.Line("if (missing is not null) { throw new global::System.NotSupportedException(\"Model '\" + ModelName + \"' uses ops that backend \" + typeof(TOps).Name + \" does not support: \" + missing); }");
        }

        w.Close();
        w.Line();
    }

