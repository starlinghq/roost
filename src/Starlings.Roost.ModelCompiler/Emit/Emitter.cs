    private static void EmitHelpers(Writer w)
    {
        w.Line("[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        w.Line("private static " + Span + " Tok(in StepContext c, long perToken, int rows, long elementsPerRow, " + DType + " dtype) =>");
        w.Line("    new " + Span + " { Address = c.Arena.Address + (nint)(perToken * c.Layout.CapacityTokens), Length = (ulong)((long)rows * elementsPerRow), Dtype = dtype };");
        w.Line("[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        w.Line("private static " + Span + " Fix(in StepContext c, long offset, long elements, " + DType + " dtype) =>");
        w.Line("    new " + Span + " { Address = c.Arena.Address + (nint)(c.Layout.FixedRegionOffset + offset), Length = (ulong)elements, Dtype = dtype };");
        w.Line();
    }

    private static string ValueExpr(OpGraph graph, BufferPlan plan, int weightCount, int id)
    {
        var v = graph.Values[id];
        switch (v.Kind)
        {
            case ValueKind.Weight:
                return "ctx.Weights[" + id.ToString(CultureInfo.InvariantCulture) + "]";
            case ValueKind.State:
                return "ctx.State[" + (id - weightCount).ToString(CultureInfo.InvariantCulture) + "]";
            case ValueKind.Input:
                return "ctx.Plan." + v.Name.Substring("plan.".Length);
            default:
                var p = plan.Placements[id];
                if (p.TokenMajor)
                {
                    return "Tok(in ctx, " + p.Offset.ToString(CultureInfo.InvariantCulture) + "L, " + (p.Rows == "selected" ? "ctx.Selected" : "ctx.Tokens") + ", " + p.ElementsPerRow.ToString(CultureInfo.InvariantCulture) + "L, " + DType + "." + p.Dtype + ")";
                }

                return "Fix(in ctx, " + p.Offset.ToString(CultureInfo.InvariantCulture) + "L, " + p.ElementsPerRow.ToString(CultureInfo.InvariantCulture) + "L, " + DType + "." + p.Dtype + ")";
        }
    }

    private static string IntExpr(string folded)
    {
        var sb = new StringBuilder();
        int i = 0;
        while (i < folded.Length)
        {
            if (DimExpression.IsNameStart(folded[i]))
            {
                int s = i;
                while (i < folded.Length && DimExpression.IsNamePart(folded[i]))
                {
                    i++;
                }

                string n = folded.Substring(s, i - s);
                switch (n)
                {
                    case "tokens":
                        sb.Append("ctx.Tokens");
                        break;
                    case "selected":
                        sb.Append("ctx.Selected");
                        break;
                    case "seqs":
                        sb.Append("ctx.Sequences");
                        break;
                    default:
                        sb.Append("ctx.KvBlocks");
                        break;
                }
            }
            else
            {
                sb.Append(folded[i]);
                i++;
            }
        }

        return sb.ToString();
    }

    private static List<(string Field, string Expr)> FieldExprs(OpGraph graph, BufferPlan plan, int weightCount, OpNode node, OpInfo op)
    {
        string[] inF = node.Attributes["in"].Length > 0 ? node.Attributes["in"].Split(',') : Array.Empty<string>();
        string[] outF = node.Attributes["out"].Length > 0 ? node.Attributes["out"].Split(',') : Array.Empty<string>();
        var result = new List<(string, string)>();
        foreach (var f in op.Fields)
        {
            int o = Array.IndexOf(outF, f.Name);
            int i = Array.IndexOf(inF, f.Name);
            if (f.Kind == FieldKind.Span)
            {
                if (o >= 0)
                {
                    result.Add((f.Name, ValueExpr(graph, plan, weightCount, node.Outputs[o])));
                }
                else if (i >= 0)
                {
                    result.Add((f.Name, ValueExpr(graph, plan, weightCount, node.Inputs[i])));
                }

                continue;
            }

            if (!node.Attributes.TryGetValue("arg." + f.Name, out string? text))
            {
                continue;
            }

            switch (f.Kind)
            {
                case FieldKind.Int:
                    result.Add((f.Name, "(int)(" + IntExpr(text) + ")"));
                    break;
                case FieldKind.Long:
                    result.Add((f.Name, "(long)(" + IntExpr(text) + ")"));
                    break;
                case FieldKind.Float:
                    result.Add((f.Name, text + "f"));
                    break;
                case FieldKind.Bool:
                    result.Add((f.Name, text));
                    break;
                default:
                    result.Add((f.Name, f.TypeName + "." + text));
                    break;
            }
        }

        return result;
    }

    private static void EmitCall(Writer w, string argsType, string opName, List<(string Field, string Expr)> fields)
    {
        w.Open();
        w.Line(argsType + " a = default;");
        foreach (var (field, expr) in fields)
        {
            w.Line("a." + field + " = " + expr + ";");
        }

        w.Line("TOps." + opName + "(in a);");
        w.Close();
    }

    private static string Expr(List<(string Field, string Expr)> fields, string field) =>
        fields.First(f => f.Field == field).Expr;

    private static bool Has(List<(string Field, string Expr)> fields, string field) =>
        fields.Any(f => f.Field == field);

    private static void EmitForward(Writer w, BuiltModel m, BufferPlan plan, Dictionary<string, OpInfo> ops, int weightCount)
    {
        w.Line("/// <summary>The identity lowering of the unfused graph: every node in order, as static calls on <typeparamref name=\"TOps\"/>. Allocates nothing; a fused op falls back to its unfused parts when the backend does not provide it.</summary>");
        w.Line("public static void Forward<TOps>(in StepContext ctx) where TOps : struct, " + Ops);
        w.Open();
        foreach (var node in m.Graph.Nodes)
        {
            var op = ops[node.Op];
            w.Line("// " + node.Id.ToString(CultureInfo.InvariantCulture) + " " + node.Op + " " + Writer.Comment(node.Attributes["node"]));
            var fields = FieldExprs(m.Graph, plan, weightCount, node, op);
            if (!op.HasSupportsFlag)
            {
                EmitCall(w, op.ArgsType, op.Name, fields);
                continue;
            }

            // AddRmsNorm (the only fused op the lowering knows): Input := rmsnorm(Input + Residual), Residual := Input + Residual.
            w.Line("if (TOps.Supports" + op.Name + ")");
            EmitCall(w, op.ArgsType, op.Name, fields);
            w.Line("else");
            w.Open();
            var residual = new List<(string, string)>
            {
                ("A", Expr(fields, "Input")),
                ("B", Expr(fields, "Residual")),
                ("Output", Expr(fields, "Residual")),
                ("Elements", "(long)(" + Expr(fields, "Rows") + ") * (" + Expr(fields, "Dim") + ")"),
            };
            if (Has(fields, "DType"))
            {
                residual.Add(("DType", Expr(fields, "DType")));
            }

            EmitCall(w, ops["Residual"].ArgsType, "Residual", residual);
            var norm = new List<(string, string)>
            {
                ("Input", Expr(fields, "Residual")),
                ("Weight", Expr(fields, "Weight")),
                ("Output", Expr(fields, "Input")),
                ("Rows", Expr(fields, "Rows")),
                ("Dim", Expr(fields, "Dim")),
            };
            if (Has(fields, "Eps"))
            {
                norm.Add(("Eps", Expr(fields, "Eps")));
            }

            if (Has(fields, "DType"))
            {
                norm.Add(("DType", Expr(fields, "DType")));
            }

            EmitCall(w, ops["RmsNorm"].ArgsType, "RmsNorm", norm);
            w.Close();
        }

        w.Close();
        w.Line();
    }

    private static void EmitOutputs(Writer w, BuiltModel m, BufferPlan plan, int weightCount)
    {
        foreach (int id in m.OutputValues)
        {
            string name = m.Graph.Values[id].Name;
            var id2 = new string(name.Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray());
            w.Line("/// <summary>The span of model output '" + Writer.Comment(name) + "' after Forward.</summary>");
            w.Line("public static " + Span + " Output_" + id2 + "(in StepContext ctx) => " + ValueExpr(m.Graph, plan, weightCount, id) + ";");
        }
    }

    private sealed class Writer
    {
        private readonly StringBuilder _sb = new StringBuilder();
        private int _indent;

        public void Line(string text = "")
        {
            if (text.Length > 0)
            {
                _sb.Append(' ', _indent * 4).Append(text);
            }

            _sb.Append('\n');
        }

        public void Open()
        {
            Line("{");
            _indent++;
        }

        public void Close()
        {
            _indent--;
            Line("}");
        }

        public override string ToString() => _sb.ToString();

        public static string Comment(string s) => s.Replace('\n', ' ').Replace('\r', ' ');

        public static string Lit(string s)
        {
            var sb = new StringBuilder("\"");
            foreach (char c in s)
            {
                switch (c)
                {
                    case '\\':
                        sb.Append("\\\\");
                        break;
                    case '"':
                        sb.Append("\\\"");
                        break;
                    case '\n':
                        sb.Append("\\n");
                        break;
                    case '\r':
                        sb.Append("\\r");
                        break;
                    default:
                        if (c < 32)
                        {
                            sb.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
                        }
                        else
                        {
                            sb.Append(c);
                        }

                        break;
                }
            }

            return sb.Append('"').ToString();
        }
    }
